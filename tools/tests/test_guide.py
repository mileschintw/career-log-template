#!/usr/bin/env python3
"""Tests for tools/guide.py, on small repos built in a temporary directory.

  python3 -I tools/tests/test_guide.py
"""
import importlib.util, os, shutil, subprocess, sys, tempfile, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
REPO = os.path.dirname(TOOLS)


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(TOOLS, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


guide = load("guide")
skill_lint = load("skill_lint")

SKILL_MD = """# Skill

## Layout

| Path | What |
|---|---|
| `README.md` | Index, see [setup](modes/setup.md) |
| `tools/` | Machine setup: [SETUP.md](../../SETUP.md) |

| Path | What |
|---|---|
| `writing.md` | A second table, left out |

## Modes

| Mode | When | For example | File |
|---|---|---|---|
| **log** | Something happened | "log this" | [modes/log.md](modes/log.md) |
| **setup** | Setup has not run | "set me up" | [modes/setup.md](modes/setup.md) |
"""

FLOWS = """<!-- flows: tools read this table -->
| Flow | Mode | Next | Why | Session |
|---|---|---|---|---|
| first use | `setup` | `log` | Then log | new |
| day to day | `log` | `scan-results` | A chain | same |
| day to day | `scan-results` | - | The end | new |
<!-- /flows -->
"""

GUIDE = """# Guide

## Flows

%s
## Modes

<!-- generated by tools/guide.py: modes; edit SKILL.md -->
<!-- /generated: modes -->

<!-- generated by tools/guide.py: direction -->
<!-- /generated: direction -->

<!-- generated by tools/guide.py: config -->
<!-- /generated: config -->

## Files

<!-- generated by tools/guide.py: files -->
<!-- /generated: files -->
""" % FLOWS

TREE = {
    "skills/career-log/SKILL.md": SKILL_MD,
    "skills/career-log/modes/log.md": "# Log\n",
    "skills/career-log/modes/setup.md": "# Setup\n",
    "skills/career-log/modes/scan-results.md": "# Scan results\n",
    "SETUP.md": "# Setup\n",
    "docs/guide.md": GUIDE,
}
COPIED = ("tools/config.py", "tools/logfiles.py", "tools/config.default.toml", "tools/template/direction.md")


class Guide(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.root)
        for rel, body in TREE.items():
            self.put(rel, body)
        for rel in COPIED:
            os.makedirs(os.path.dirname(self.path(rel)), exist_ok=True)
            shutil.copy(os.path.join(REPO, *rel.split("/")), self.path(rel))

    def path(self, rel):
        return os.path.join(self.root, *rel.split("/"))

    def put(self, rel, body, newline="\n"):
        os.makedirs(os.path.dirname(self.path(rel)), exist_ok=True)
        with open(self.path(rel), "w", encoding="utf-8", newline=newline) as f:
            f.write(body)

    def get(self, rel):
        with open(self.path(rel), encoding="utf-8") as f:
            return f.read()

    def replace(self, rel, old, new):
        text = self.get(rel)
        self.assertIn(old, text)
        self.put(rel, text.replace(old, new, 1))

    def run_tool(self, *args):
        p = subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "guide.py"), *args, "--root", self.root],
                           capture_output=True, text=True, encoding="utf-8")
        return p.returncode, p.stdout

    def messages(self):
        return [m for _, _, m in guide.problems(self.root)]

    def test_write_then_check_passes(self):
        self.assertEqual(self.run_tool("check")[0], 1)
        self.assertEqual(self.run_tool("write"), (0, "wrote docs/guide.md\n"))
        self.assertEqual(self.run_tool("check"), (0, ""))
        self.assertEqual(self.run_tool("write"), (0, "unchanged docs/guide.md\n"))

    def test_blocks_hold_their_sources(self):
        self.run_tool("write")
        text = self.get("docs/guide.md")
        self.assertIn('| **log** | "log this" | Something happened |', text)
        self.assertIn("| `README.md` | Index, see [setup](../skills/career-log/modes/setup.md) |", text)
        self.assertIn("[SETUP.md](../SETUP.md)", text)
        self.assertNotIn("A second table", text)
        self.assertIn('| `record_language` | The language Log files are written in. | one line of text | `"English"` |', text)
        self.assertIn("`fit_budget`: a whole number from 1 to 50", text)
        self.assertIn("| Target roles | `direction.md › Target roles, ranked` |", text)
        self.assertIn("`direction.md › Employer preferences`, its `**Sorting order` line", text)

    def test_changed_mode_row_is_stale_until_written(self):
        self.run_tool("write")
        self.replace("skills/career-log/SKILL.md", '"log this"', '"log this to my log"')
        self.assertEqual(self.messages(), ["block modes is stale; run `python3 -I tools/guide.py write`"])
        code, out = self.run_tool("check")
        self.assertEqual(code, 1)
        self.assertRegex(out, r"^docs/guide\.md:\d+: block modes is stale")
        self.run_tool("write")
        self.assertEqual(self.messages(), [])

    def test_changed_config_field_is_stale_until_written(self):
        self.run_tool("write")
        self.replace("tools/config.default.toml", "window = 7", "window = 14")
        self.assertEqual(self.messages(), ["block config is stale; run `python3 -I tools/guide.py write`"])
        self.run_tool("write")
        self.assertIn("`window`: `14`", self.get("docs/guide.md"))
        self.assertEqual(self.messages(), [])

    def test_changed_allowed_values_and_direction_are_stale(self):
        self.run_tool("write")
        self.replace("tools/config.py", '"interviewer_profiles": ("never", "always")', '"interviewer_profiles": ("never", "always", "ask")')
        self.replace("tools/template/direction.md", "Setup fills it; empty until then.", "Setup fills it.")
        self.assertEqual(sorted(self.messages()), ["block config is stale; run `python3 -I tools/guide.py write`",
                                                   "block direction is stale; run `python3 -I tools/guide.py write`"])

    def test_crlf_checkout_reads_as_current(self):
        self.run_tool("write")
        self.put("docs/guide.md", self.get("docs/guide.md"), newline="\r\n")
        self.assertEqual(self.messages(), [])

    def test_missing_and_unbalanced_blocks(self):
        self.replace("docs/guide.md", "<!-- generated by tools/guide.py: files -->\n<!-- /generated: files -->\n", "")
        self.run_tool("write")
        self.assertEqual(self.messages(), ["no generated block files"])
        self.replace("docs/guide.md", "<!-- /generated: modes -->\n", "")
        self.assertIn("opens inside block modes", self.messages()[0])

    def test_second_block_of_a_name_fails(self):
        self.replace("docs/guide.md", "<!-- generated by tools/guide.py: files -->", "<!-- generated by tools/guide.py: modes -->")
        self.replace("docs/guide.md", "<!-- /generated: files -->", "<!-- /generated: modes -->")
        self.assertIn("a second block modes", self.messages()[0])

    def test_missing_source_is_a_problem_not_a_crash(self):
        os.remove(self.path("tools/template/direction.md"))
        self.assertEqual(len(self.messages()), 1)
        self.assertEqual(self.run_tool("check")[0], 1)

    def test_shared_direction_section_is_one_row(self):
        self.run_tool("write")
        self.assertIn("| Work authorisation, visa sponsorship, other hard constraints | `direction.md › Constraints` |", self.get("docs/guide.md"))

    def test_field_without_default_fails(self):
        self.replace("tools/config.default.toml", "m = 5\n", "")
        self.assertEqual(self.messages(), ["config.default.toml lacks m"])

    def test_flows_rows(self):
        rows = guide.flows(self.root)
        self.assertEqual([(r["flow"], r["mode"], r["next"], r["session"]) for r in rows],
                         [("first use", "setup", "log", "new"), ("day to day", "log", "scan-results", "same"),
                          ("day to day", "scan-results", "-", "new")])
        code, out = self.run_tool("flows")
        self.assertEqual((code, out.splitlines()[0]), (0, "first use\tsetup\tlog\tThen log\tnew"))

    def test_bad_flows_rows(self):
        self.run_tool("write")
        self.replace("docs/guide.md", "| first use | `setup` | `log` | Then log | new |", "| first use | `setup` | `apply` | Then log | later |")
        self.assertEqual(self.messages(), ["flows: next 'apply' is no mode in SKILL.md › Modes or modes/",
                                           "flows: session must be new or same, not 'later'"])
        self.replace("docs/guide.md", "| Flow | Mode | Next | Why | Session |", "| Flow | Mode | Next | Session |")
        self.assertIn("columns are Flow | Mode | Next | Why | Session", self.messages()[0])

    def test_skill_lint_reports_a_stale_guide(self):
        self.run_tool("write")
        self.replace("skills/career-log/SKILL.md", '"set me up"', '"set this up"')
        found = [(f, m) for f, _, m in skill_lint.Linter(self.root).run()]
        self.assertIn(("docs/guide.md", "block modes is stale; run `python3 -I tools/guide.py write`"), found)

    def test_repo_guide_is_current(self):
        """The guide in this repo matches its sources as committed."""
        p = subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "guide.py"), "check"],
                           capture_output=True, text=True, encoding="utf-8")
        self.assertEqual((p.returncode, p.stdout), (0, ""))


if __name__ == "__main__":
    unittest.main()
