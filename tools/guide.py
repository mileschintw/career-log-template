#!/usr/bin/env python3
"""Write and check the generated blocks of docs/guide.md, and read its flows table.

  python3 -I tools/guide.py write      (Windows: py -3 -I tools/guide.py ...)
  python3 -I tools/guide.py check
  python3 -I tools/guide.py flows

Each takes --root <root>, the repo's root (default: the repo this script is in).

The guide keeps four tables as generated blocks, each between a line
`<!-- generated by tools/guide.py: <name> ... -->` and a line `<!-- /generated: <name> -->`, written
from its single source:
- modes: SKILL.md › Modes (mode, example requests, when);
- config: tools/config.default.toml (each field's comment and default) and tools/config.py (FIELDS,
  the allowed values);
- direction: tools/config.py (DIRECTION) and the section it names in tools/template/direction.md;
- files: SKILL.md › Layout, then the `## Files` table of each other skill file that has one
  (the skill's folder, then modes/, each in name order): the files only that file's work uses.
Relative links in a source are rewritten to point from docs/.

write: rewrites every block from its source and prints `wrote <file>` or `unchanged <file>`.
check: prints one `<file>:<line>: <problem>` line per stale or missing block and per bad flows row,
then exits 1; prints nothing and exits 0 when the guide is current. tools/skill_lint.py runs it.
flows: the flows table (between `<!-- flows ... -->` and `<!-- /flows -->`), one tab-separated
line per row: flow, mode, next, why, session. Next is `-` on a flow's last step; session is `new`
(the next mode is best started in a fresh session or after `/clear`) or `same` (it goes on in this
one). flows() returns the same rows to an importer.

Exit 0 on success, 1 on a stale guide or bad flows table, 2 on a bad argument. Standard library
only, Python 3.11+.
"""
import importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
GUIDE = "docs/guide.md"
SKILL_MD = "skills/career-log/SKILL.md"
DIRECTION_MD = "tools/template/direction.md"
BLOCKS = ("modes", "config", "direction", "files")
SESSIONS = ("new", "same")
END = "-"   # the Next of a flow's last step

OPEN = re.compile(r"^<!-- generated by tools/guide\.py: ([a-z]+)\b.*-->$")
CLOSE = re.compile(r"^<!-- /generated: ([a-z]+) -->$")
LINK = re.compile(r"\]\(([^)\s]+)\)")


class GuideError(Exception):
    pass


def read(path):
    with open(path, encoding="utf-8-sig") as f:   # text mode: a CRLF checkout reads as LF
        return f.read()


def module(root, name):
    """tools/<name>.py under root, imported fresh: a test root has its own."""
    spec = importlib.util.spec_from_file_location("guide_" + name, os.path.join(root, "tools", name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def cells(line):
    return [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]


def table(text, heading):
    """The rows (lists of cells) of the first table under `## <heading>`, header and rule left out."""
    m = re.search(r"^## %s\n(.*?)(?=^## |\Z)" % re.escape(heading), text, re.M | re.S)
    if not m:
        raise GuideError("no `## %s` section" % heading)
    rows = []
    for line in m.group(1).splitlines():
        if line.startswith("|"):
            rows.append(cells(line))
        elif rows:
            break
    if len(rows) < 2:
        raise GuideError("no table under `## %s`" % heading)
    return rows[0], rows[2:]


def rebase(text, src_dir, root):
    """text with each relative link rewritten from src_dir (relative to root) to docs/."""
    def fix(m):
        href = m.group(1)
        if re.match(r"[a-z][a-z0-9+.-]*:", href, re.I) or href.startswith("#") or "<" in href:
            return m.group(0)
        path, _, frag = href.partition("#")
        target = os.path.normpath(os.path.join(root, src_dir, *path.split("/")))
        new = os.path.relpath(target, os.path.join(root, "docs")).replace(os.sep, "/")
        return "](%s%s)" % (new, "#" + frag if frag else "")
    return LINK.sub(fix, text)


def render(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def modes_block(root):
    header, rows = table(read(os.path.join(root, *SKILL_MD.split("/"))), "Modes")
    col = {h.lower(): i for i, h in enumerate(header)}
    for need in ("mode", "when", "for example"):
        if need not in col:
            raise GuideError("SKILL.md › Modes has no `%s` column" % need)
    src = os.path.dirname(SKILL_MD)
    return render(["Mode", "Say, for example", "When"],
                  [[r[col["mode"]], rebase(r[col["for example"]], src, root), rebase(r[col["when"]], src, root)]
                   for r in rows])


def files_block(root):
    src = os.path.dirname(SKILL_MD)
    header, rows = table(read(os.path.join(root, *SKILL_MD.split("/"))), "Layout")
    out = [[r[0], rebase(r[1], src, root)] for r in rows]
    for folder in (src, src + "/modes"):
        here = os.path.join(root, *folder.split("/"))
        for name in sorted(os.listdir(here)) if os.path.isdir(here) else []:
            path = os.path.join(here, name)
            if name.endswith(".md") and folder + "/" + name != SKILL_MD and os.path.isfile(path):
                text = read(path)
                if re.search(r"^## Files$", text, re.M):
                    out += [[r[0], rebase(r[1], folder, root)] for r in table(text, "Files")[1]]
    return render(["Path", "What"], out)


def config_block(root):
    """One row per comment group of config.default.toml: its fields, what they do, values, defaults."""
    import tomllib
    cfg = module(root, "config")
    path = os.path.join(root, "tools", "config.default.toml")
    text = read(path)
    defaults = tomllib.loads(text)
    groups, comment, fields = [], [], []
    for line in text.splitlines() + [""]:
        s = line.strip()
        if s.startswith("#"):
            if fields:
                groups.append((comment, fields))
                comment, fields = [], []
            comment.append(s.lstrip("#").strip())
        elif re.match(r"[A-Za-z_]+\s*=", s):
            fields.append(s.split("=", 1)[0].strip())
        elif not s:
            if fields:
                groups.append((comment, fields))
            comment, fields = [], []
    rows = []
    for comment, names in groups:
        for f in names:
            if f not in cfg.FIELDS:
                raise GuideError("config.default.toml: %s is not in config.py FIELDS" % f)
        allowed = [cfg.allowed_text(cfg.FIELDS[f]) if cfg.FIELDS[f] else "one line of text" for f in names]
        many = len(names) > 1
        rows.append([
            "<br>".join("`%s`" % f for f in names),
            rebase(" ".join(comment), ".", root),
            "<br>".join(("`%s`: " % f if many else "") + a for f, a in zip(names, allowed)),
            "<br>".join(("`%s`: " % f if many else "") + "`%s`" % cfg.toml_value(defaults[f]) for f in names),
        ])
    missing = [f for f in cfg.FIELDS if f not in defaults]
    if missing:
        raise GuideError("config.default.toml lacks %s" % ", ".join(missing))
    return render(["Field", "What it does", "Values", "Default"], rows)


def direction_block(root):
    """One row per Direction item: where it lives in direction.md and what its section holds there."""
    cfg = module(root, "config")
    text = read(os.path.join(root, *DIRECTION_MD.split("/")))
    sections = {}
    for m in re.finditer(r"^## ([^\n]+)\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        body = re.sub(r"<!--\s*(.*?)\s*-->", r"\1", m.group(2), flags=re.S)
        sections[m.group(1).strip()] = re.sub(r"\s+", " ", body).strip()
    rows, at = [], {}
    for item, where in cfg.DIRECTION.items():
        heading = max((h for h in sections if where == h or where.startswith(h + ",")), key=len, default=None)
        if heading is None:
            raise GuideError("config.py DIRECTION: %s names `%s`, which is no section of %s" % (item, where, DIRECTION_MD))
        if where in at:   # items that share a place share a row
            at[where][0] += ", " + item
            continue
        at[where] = [item[0].upper() + item[1:], "`direction.md › %s`%s" % (heading, where[len(heading):]),
                     rebase(sections[heading], ".", root)]   # the Template's direction.md sits at the root
        rows.append(at[where])
    return render(["Item", "Where it lives", "What it holds"], rows)


MAKERS = {"modes": modes_block, "config": config_block, "direction": direction_block, "files": files_block}


def blocks(text):
    """{name: (first line number, start index, end index)} of the generated blocks' bodies, in lines."""
    lines = text.split("\n")
    found, open_at = {}, None
    for i, line in enumerate(lines):
        o, c = OPEN.match(line), CLOSE.match(line)
        if o:
            if open_at is not None:
                raise GuideError("line %d: block %s opens inside block %s" % (i + 1, o.group(1), open_at[0]))
            if o.group(1) in found:
                raise GuideError("line %d: a second block %s" % (i + 1, o.group(1)))
            open_at = (o.group(1), i)
        elif c:
            if open_at is None or open_at[0] != c.group(1):
                raise GuideError("line %d: block %s closes without opening" % (i + 1, c.group(1)))
            found[open_at[0]] = (open_at[1] + 1, open_at[1] + 1, i)
            open_at = None
    if open_at is not None:
        raise GuideError("line %d: block %s never closes" % (open_at[1] + 1, open_at[0]))
    return found


def generate(root, text):
    """text with every block it holds rewritten; GuideError on a block name it does not know."""
    lines = text.split("\n")
    found = blocks(text)
    for name in sorted(found, key=lambda n: -found[n][1]):
        if name not in MAKERS:
            raise GuideError("line %d: no generated block is named %s" % (found[name][0], name))
        _, start, end = found[name]
        lines[start:end] = MAKERS[name](root).split("\n")
    return "\n".join(lines)


def flows(root, text=None):
    """The flows table's rows as dicts (flow, mode, next, why, session, line); GuideError when it is missing."""
    if text is None:
        text = read(os.path.join(root, *GUIDE.split("/")))
    lines = text.split("\n")
    start = next((i for i, l in enumerate(lines) if re.match(r"^<!-- flows\b.*-->$", l)), None)
    if start is None:
        raise GuideError("no `<!-- flows -->` block")
    rows, header = [], None
    for i in range(start + 1, len(lines)):
        line = lines[i]
        if line == "<!-- /flows -->":
            return rows
        if not line.startswith("|"):
            continue
        c = cells(line)
        if header is None:
            header = [h.lower() for h in c]
            if header != ["flow", "mode", "next", "why", "session"]:
                raise GuideError("line %d: the flows table's columns are Flow | Mode | Next | Why | Session" % (i + 1))
        elif not set(line) <= set("|-: "):
            row = dict(zip(header, c))
            row = {k: v.strip("`") if k in ("mode", "next", "session") else v for k, v in row.items()}
            row["line"] = i + 1
            rows.append(row)
    raise GuideError("line %d: the flows block never closes" % (start + 1))


def known_modes(root):
    _, rows = table(read(os.path.join(root, *SKILL_MD.split("/"))), "Modes")
    names = {re.sub(r"\*", "", r[0]) for r in rows}
    modes_dir = os.path.join(root, "skills", "career-log", "modes")
    return names | {f[:-3] for f in os.listdir(modes_dir) if f.endswith(".md")}


def problems(root):
    """(file, line, message) for each stale or missing block and each bad flows row."""
    path = os.path.join(root, *GUIDE.split("/"))
    out = []
    try:
        text = read(path)
        found = blocks(text)
        current = generate(root, text)
    except (GuideError, OSError) as e:
        return [(GUIDE, 0, str(e))]
    for name in BLOCKS:
        if name not in found:
            out.append((GUIDE, 0, "no generated block %s" % name))
    if current != text:
        new = blocks(current)
        old_lines, new_lines = text.split("\n"), current.split("\n")
        for name, (line, start, end) in sorted(found.items(), key=lambda kv: kv[1][0]):
            _, s2, e2 = new[name]
            if old_lines[start:end] != new_lines[s2:e2]:
                out.append((GUIDE, line, "block %s is stale; run `python3 -I tools/guide.py write`" % name))
    try:
        rows, modes = flows(root, text), known_modes(root)
    except (GuideError, OSError) as e:
        return out + [(GUIDE, 0, str(e))]
    if not rows:
        out.append((GUIDE, 0, "the flows table has no rows"))
    for r in rows:
        for key in ("mode", "next"):
            if r.get(key) not in modes and not (key == "next" and r.get(key) == END):
                out.append((GUIDE, r["line"], "flows: %s %r is no mode in SKILL.md › Modes or modes/" % (key, r.get(key))))
        if r.get("session") not in SESSIONS:
            out.append((GUIDE, r["line"], "flows: session must be %s, not %r" % (" or ".join(SESSIONS), r.get("session"))))
        if not r.get("flow") or not r.get("why"):
            out.append((GUIDE, r["line"], "flows: flow and why must not be empty"))
    return out


def main(argv):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    args = list(argv)
    if "-h" in args or "--help" in args:
        print(__doc__.rstrip())
        return 0
    root = os.path.dirname(HERE)
    if "--root" in args:
        i = args.index("--root")
        if i + 1 >= len(args):
            print("usage: --root needs a path")
            return 2
        root = args[i + 1]
        del args[i:i + 2]
    if args not in (["write"], ["check"], ["flows"]):
        print("usage: guide.py write | check | flows  [--root <root>]")
        return 2
    path = os.path.join(root, *GUIDE.split("/"))
    if args[0] == "write":
        try:
            text = read(path)
            new = generate(root, text)
        except (GuideError, OSError) as e:
            print("guide: %s" % e)
            return 1
        if new != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(new)
        print("%s %s" % ("wrote" if new != text else "unchanged", GUIDE))
        return 0
    if args[0] == "check":
        found = problems(root)
        for f, n, msg in found:
            print("%s:%d: %s" % (f, n, msg))
        return 1 if found else 0
    try:
        rows = flows(root)
    except (GuideError, OSError) as e:
        print("guide: %s" % e)
        return 1
    for r in rows:
        print("\t".join(r[k] for k in ("flow", "mode", "next", "why", "session")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
